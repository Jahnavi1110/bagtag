/** Detect an image type from its first bytes ("magic numbers"), ignoring the file name and the browser-supplied MIME type. */
export type ImageType = { ext: "png" | "jpg" | "webp" | "gif"; mime: string };

export const MAX_UPLOAD_BYTES = 2 * 1024 * 1024;

export function detectImageType(bytes: Uint8Array): ImageType | null {
  const starts = (sig: number[], offset = 0) => sig.every((b, i) => bytes[offset + i] === b);
  if (starts([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])) return { ext: "png", mime: "image/png" };
  if (starts([0xff, 0xd8, 0xff])) return { ext: "jpg", mime: "image/jpeg" };
  if (starts([0x47, 0x49, 0x46, 0x38])) return { ext: "gif", mime: "image/gif" };
  if (starts([0x52, 0x49, 0x46, 0x46]) && starts([0x57, 0x45, 0x42, 0x50], 8)) return { ext: "webp", mime: "image/webp" };
  return null;
}

const MIME_BY_EXT: Record<string, string> = { png: "image/png", jpg: "image/jpeg", gif: "image/gif", webp: "image/webp" };
export const mimeForFile = (name: string) => MIME_BY_EXT[name.split(".").pop() ?? ""] ?? null;

/** Upload names are generated by us: 21 nanoid chars + known extension. Anything else is rejected (no path traversal). */
export const UPLOAD_NAME_RE = /^[A-Za-z0-9_-]{21}\.(png|jpg|gif|webp)$/;
